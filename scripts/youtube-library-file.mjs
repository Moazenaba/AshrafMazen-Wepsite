// The one place that writes src/data/youtube-library.ts (the saved channel library the site imports), so the manual
// build (build-youtube-library.mjs) and the automatic job (refresh-youtube-library.mjs) produce exactly the same file.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const libraryPath = resolve(root, 'src/data/youtube-library.ts');

export const libraryFileSource = (library) => `// Generated by scripts/build-youtube-library.mjs. Do not edit by hand.

export interface LibraryVideo {
  id: string;
  title: string;
  published?: string;
}

export interface LibraryPlaylist {
  id: string;
  title: string;
  count: string;
  latestVideoId: string;
  videos: LibraryVideo[];
}

export const YOUTUBE_LIBRARY: LibraryPlaylist[] = ${JSON.stringify(library, null, 2)};
`;

// The saved library as data (the file is TypeScript declarations followed by one JSON array)
export function readLibraryFile() {
  const source = readFileSync(libraryPath, 'utf8');
  const start = source.indexOf('= [', source.indexOf('export const YOUTUBE_LIBRARY'));
  return JSON.parse(source.slice(start + 2, source.lastIndexOf('];') + 1));
}

// Writes the file only when its content changes; returns whether it did
export function writeLibraryFile(library) {
  const next = libraryFileSource(library);
  if (readFileSync(libraryPath, 'utf8') === next) return false;
  writeFileSync(libraryPath, next, 'utf8');
  return true;
}
